    lookup = Dict{String,ModelSpec}()
    for spec in MODEL_SPECS
        lookup[_normalize_model_lookup_key(spec.name)] = spec
        lookup[_normalize_model_lookup_key(spec.directory)] = spec
        for alias in spec.aliases
            lookup[_normalize_model_lookup_key(alias)] = spec
        end
        run_name = String(spec.run_symbol)
        lookup[_normalize_model_lookup_key(run_name)] = spec
        startswith(run_name, "run_") && (lookup[_normalize_model_lookup_key(run_name[5:end])] = spec)
    end
    lookup
end

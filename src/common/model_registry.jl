# This file is the structured source of truth for ArkModelZoo model metadata,
# load order, and per-model public exports.

"""
    ModelSpec

Lightweight metadata describing one ArkModelZoo model entry point and its
public API surface.
"""
Base.@kwdef struct ModelSpec
    name::String
    title::String
    category::String
    directory::String
    params_symbol::Symbol
    run_symbol::Symbol
    exports::Tuple{Vararg{Symbol}}
    aliases::Tuple{Vararg{String}} = ()
end

function _normalize_model_lookup_key(name::Union{AbstractString,Symbol})
    key = lowercase(strip(String(name)))
    startswith(key, "run_") && (key = key[5:end])
    return replace(key, r"[^a-z0-9]+" => "")
end

